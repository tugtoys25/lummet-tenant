// Builds static/css/public.css: the stylesheets every PUBLIC page links, joined in base.html's order into one file.
//
// Why: 12 separate stylesheets are 12 requests that must all finish before a page can paint. Public pages now link this
// one file (worker/render/assets.js selectAssetSet swaps the 12 links for it); the dashboard still links the separate files.
// The list and the order come from templates/layout/base.html, so adding a stylesheet there and re-running this is enough.
//
//   node scripts/build-public-css.mjs          write static/css/public.css
//   node scripts/build-public-css.mjs --check  exit 1 if it is out of date
//
// Order of work after changing any stylesheet:  node scripts/build-css.mjs  &&  node scripts/build-public-css.mjs  &&  node scripts/asset-version.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { publicStylesheets } from "../worker/render/assets.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Removes comments and extra whitespace. Strings are left exactly as written; spaces inside (...) are only collapsed,
 * never removed (calc(1px + 2px) needs them). Nothing else is rewritten: no merging of rules, no value changes.
 */
export function minifyCss(css) {
  let out = "";
  let i = 0;
  const n = css.length;
  let pendingSpace = false;
  const SPACE_AROUND = new Set(["{", "}", ";", ","]);
  const push = (chunk) => {
    if (pendingSpace) {
      const last = out[out.length - 1];
      if (last !== undefined && !SPACE_AROUND.has(last) && !SPACE_AROUND.has(chunk[0])) out += " ";
      pendingSpace = false;
    }
    out += chunk;
  };
  while (i < n) {
    const c = css[i];
    if (c === "/" && css[i + 1] === "*") {
      const end = css.indexOf("*/", i + 2);
      i = end === -1 ? n : end + 2;
      pendingSpace = true;
      continue;
    }
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (j < n && css[j] !== c) { if (css[j] === "\\") j++; j++; }
      push(css.slice(i, j + 1));
      i = j + 1;
      continue;
    }
    if (c === "u" && css.startsWith("url(", i)) {
      // url(...) is copied as is, so a data: URI or an unquoted path is never touched
      const end = css.indexOf(")", i);
      const j = end === -1 ? n : end + 1;
      push(css.slice(i, j));
      i = j;
      continue;
    }
    if (/\s/.test(c)) { pendingSpace = true; i++; continue; }
    if (c === "}" && out.endsWith(";")) out = out.slice(0, -1); // last declaration needs no ;
    push(c);
    i++;
  }
  return out;
}

export function buildPublicCss(base = root) {
  const html = readFileSync(join(base, "templates", "layout", "base.html"), "utf8");
  const names = publicStylesheets(html);
  if (!names.length) throw new Error("no public stylesheets found in templates/layout/base.html");
  const body = names.map((name) => `/* ${name}.css */\n` + minifyCss(readFileSync(join(base, "static", "css", `${name}.css`), "utf8")) + "\n").join("");
  return `/* GENERATED by scripts/build-public-css.mjs from the stylesheets base.html links (${names.join(", ")}). Do not edit by hand. */\n${body}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(root, "static", "css", "public.css");
  const want = buildPublicCss();
  const have = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (have !== want) { console.error("static/css/public.css is out of date. Run: node scripts/build-public-css.mjs"); process.exit(1); }
    console.log("public.css is current");
  } else if (have !== want) {
    writeFileSync(out, want);
    console.log(`written static/css/public.css (${(want.length / 1024).toFixed(0)} KB)`);
  } else console.log("public.css is current");
}
