// Writes migrations/0014_seed_site_text.sql from worker/site-text/registry.js (the single source of the default wording).
//   node scripts/generate-site-text-seed.mjs          write the file
//   node scripts/generate-site-text-seed.mjs --check  exit 1 if the file is out of date
// INSERT OR IGNORE: a value an owner already edited is never overwritten, and running it twice changes nothing.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ALL_TEXT_FIELDS, TEXT_DEFAULTS } from "../worker/site-text/registry.js";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "migrations", "0014_seed_site_text.sql");
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

export function buildSeedSql() {
  const lines = [
    "-- Seeded, editable wording for the homepage lists, public sidebar, landing pages and footer.",
    "-- Generated by scripts/generate-site-text-seed.mjs from worker/site-text/registry.js. Do not edit by hand.",
    "-- INSERT OR IGNORE: values an owner already changed are never overwritten; safe to run twice.",
  ];
  for (const f of ALL_TEXT_FIELDS) lines.push(`INSERT OR IGNORE INTO settings (key, value) VALUES (${q(f.key)}, ${q(TEXT_DEFAULTS[f.key])});`);
  return lines.join("\n") + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = buildSeedSql();
  if (process.argv.includes("--check")) {
    const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (have !== want) { console.error("migrations/0014_seed_site_text.sql is out of date. Run: node scripts/generate-site-text-seed.mjs"); process.exit(1); }
  } else { writeFileSync(OUT, want); console.log(`written ${OUT} (${ALL_TEXT_FIELDS.length} settings)`); }
}
