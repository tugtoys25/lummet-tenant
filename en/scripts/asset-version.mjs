// Computes a short content hash of /static/css and /static/js and writes it
// to worker/asset-version.js. The worker appends it as ?v=<hash> to every
// stylesheet/script URL it renders, so a release is picked up immediately
// while unchanged files stay cached for a year.
//
//   node scripts/asset-version.mjs          write worker/asset-version.js
//   node scripts/asset-version.mjs --check  exit 1 if it is out of date
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "worker", "asset-version.js");

export function computeAssetVersion(base = root) {
  const h = createHash("sha256");
  const walk = (rel) => {
    const full = join(base, "static", rel);
    if (!existsSync(full)) return;
    for (const entry of readdirSync(full, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
      if (entry.isDirectory()) { walk(`${rel}/${entry.name}`); continue; }
      if (!/\.(css|js)$/.test(entry.name)) continue;
      h.update(`${rel}/${entry.name}\0`);
      h.update(readFileSync(join(full, entry.name)));
      h.update("\0");
    }
  };
  for (const dir of ["css", "js"]) walk(dir);
  return h.digest("hex").slice(0, 10);
}

export function renderModule(version) {
  return `// GENERATED by scripts/asset-version.mjs -- do not edit by hand.\n// Run: node scripts/asset-version.mjs\nexport const ASSET_VERSION = "${version}";\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = renderModule(computeAssetVersion());
  const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (have !== want) {
      console.error("worker/asset-version.js is out of date. Run: node scripts/asset-version.mjs");
      process.exit(1);
    }
    console.log("asset version is current");
  } else {
    writeFileSync(OUT, want);
    console.log("asset version written:", want.match(/"(.+)"/)[1]);
  }
}
